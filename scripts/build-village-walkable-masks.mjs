const formatBase64 = (value, width = 120) => (
  value.match(new RegExp(`.{1,${width}}`, 'g')).map((line) => `  '${line}'`).join(' +\n')
)

async function buildMask(config) {
  const source = await fs.readFile(path.join(ROOT, config.sourceAsset))
  const sourceSha256 = crypto.createHash('sha256').update(source).digest('hex')
  const image = sharp(source, { failOn: 'error', limitInputPixels: config.width * config.height })
  const metadata = await image.metadata()
  if (metadata.format !== 'png' || metadata.width !== config.width || metadata.height !== config.height) {
    throw new Error(`${config.villageId}: expected ${config.width}x${config.height} PNG, received ${metadata.width}x${metadata.height} ${metadata.format}`)
  }
  const { data, info } = await image.ensureAlpha().raw().toBuffer({ resolveWithObject: true })
  if (info.channels !== 4) throw new Error(`${config.villageId}: expected RGBA decode`)
  const pixelCount = config.width * config.height
  const bitset = Buffer.alloc(Math.ceil(pixelCount / 8))
  let whitePixels = 0
  let blackPixels = 0
  for (let index = 0; index < pixelCount; index += 1) {
    const offset = index * 4
    const rgba = [...data.subarray(offset, offset + 4)]
    const white = rgba[0] === 255 && rgba[1] === 255 && rgba[2] === 255 && rgba[3] === 255
    const black = rgba[0] === 0 && rgba[1] === 0 && rgba[2] === 0 && rgba[3] === 255
    if (!white && !black) {
      const column = index % config.width
      const row = Math.floor(index / config.width)
      throw new Error(`${config.villageId}: non-binary pixel at (${column}, ${row}): rgba(${rgba.join(', ')})`)
    }
    if (white) {
      bitset[index >> 3] |= 1 << (7 - (index & 7))
      whitePixels += 1
    } else blackPixels += 1
  }

  const moduleSource = `// Generated by scripts/build-village-walkable-masks.mjs. Do not edit by hand.\n` +
`import { createWorldTransform, worldPointToMaskCell } from '../villageWorldTransform.mjs'\n\n` +
`export const WALKABLE_MASK_METADATA = Object.freeze({\n` +
`  villageId: '${config.villageId}',\n` +
`  width: ${config.width},\n` +
`  height: ${config.height},\n` +
`  baseCellSize: ${config.baseCellSize},\n` +
`  baseWorldWidth: ${config.baseWorldWidth},\n` +
`  baseWorldHeight: ${config.baseWorldHeight},\n` +
`  playerFootWidth: ${config.playerFootWidth},\n` +
`  playerFootHeight: ${config.playerFootHeight},\n` +
`  sourceAsset: '${config.sourceAsset}',\n` +
`  sourceSha256: '${sourceSha256}',\n` +
`  formatVersion: 2,\n` +
`  encoding: '1-bit-msb-row-major-base64',\n` +
`  whitePixels: ${whitePixels},\n` +
`  blackPixels: ${blackPixels},\n` +
`  byteLength: ${bitset.length},\n` +
`})\n\n` +
`const WALKABLE_BITS_BASE64 =\n${formatBase64(bitset.toString('base64'))}\n` +
`const WALKABLE_BYTES = Uint8Array.from(globalThis.atob(WALKABLE_BITS_BASE64), (value) => value.charCodeAt(0))\n\n` +
`export function isMaskCellWalkable(column, row) {\n` +
`  if (!Number.isInteger(column) || !Number.isInteger(row) || column < 0 || row < 0 || column >= WALKABLE_MASK_METADATA.width || row >= WALKABLE_MASK_METADATA.height) return false\n` +
`  const index = row * WALKABLE_MASK_METADATA.width + column\n` +
`  return Boolean(WALKABLE_BYTES[index >> 3] & (1 << (7 - (index & 7))))\n` +
`}\n\n` +
`export function isMaskPointWalkable(worldX, worldY, currentWorldWidth = WALKABLE_MASK_METADATA.baseWorldWidth, currentWorldHeight = WALKABLE_MASK_METADATA.baseWorldHeight) {\n` +
`  const transform = createWorldTransform({ baseWorldWidth: WALKABLE_MASK_METADATA.baseWorldWidth, baseWorldHeight: WALKABLE_MASK_METADATA.baseWorldHeight, currentWorldWidth, currentWorldHeight })\n` +
`  const cell = worldPointToMaskCell(worldX, worldY, transform, WALKABLE_MASK_METADATA.width, WALKABLE_MASK_METADATA.height)\n` +
`  return cell ? isMaskCellWalkable(cell.column, cell.row) : false\n` +
`}\n`

  return { ...config, sourceSha256, whitePixels, blackPixels, byteLength: bitset.length, moduleSource }
}

const results = []
for (const config of MASKS) {
  const result = await buildMask(config)
  const outputPath = path.join(ROOT, config.outputModule)
  if (process.argv.includes('--check')) {
    const existing = await fs.readFile(outputPath, 'utf8').catch(() => '')
    if (existing !== result.moduleSource) throw new Error(`${config.outputModule} is missing or stale`)
  } else {
    await fs.mkdir(path.dirname(outputPath), { recursive: true })
    await fs.writeFile(outputPath, result.moduleSource)
  }
  results.push({
    villageId: result.villageId,
    sourceAsset: result.sourceAsset,
    outputModule: result.outputModule,
    sourceSha256: result.sourceSha256,
    whitePixels: result.whitePixels,
    blackPixels: result.blackPixels,
    byteLength: result.byteLength,
  })
}

console.log(JSON.stringify({ ok: true, mode: process.argv.includes('--check') ? 'check' : 'write', masks: results }, null, 2))
