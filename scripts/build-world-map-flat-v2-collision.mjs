import { mkdir, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import sharp from 'sharp'
import {
  WORLD_COLLISION_CELL_SIZE,
  WORLD_MAP_V4_COLLISION_OBJECTS,
  WORLD_PLAYER_FOOT_CLEARANCE,
  buildCollisionMasks,
} from '../lib/worldMapCollision.mjs'
import { WORLD_MAP_FLAT_V2_COLLISION_HOME } from '../lib/worldMapFlatV2.mjs'
import { WORLD_MAP_V4 } from '../lib/worldMapV4Manifest.mjs'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const OUTPUT = path.join(ROOT, 'public/assets/world/spring-sound-archive-garden-flat-v2')
const MODULE = path.join(ROOT, 'lib/worldMapFlatV2WalkableMaskData.mjs')
const CELL_SIZE = WORLD_COLLISION_CELL_SIZE
const WIDTH = WORLD_MAP_V4.width / CELL_SIZE
const HEIGHT = WORLD_MAP_V4.height / CELL_SIZE

const collisionObjects = WORLD_MAP_V4_COLLISION_OBJECTS.map(object => (
  object.objectId === 'landmark-home' ? WORLD_MAP_FLAT_V2_COLLISION_HOME : object
))
const masks = buildCollisionMasks(collisionObjects, WORLD_MAP_V4.width, WORLD_MAP_V4.height, {
  cellSize: CELL_SIZE,
  ...WORLD_PLAYER_FOOT_CLEARANCE,
})
const clearance = Uint8Array.from(masks.obstacle, value => value ? 0 : 1)
const packed = new Uint8Array(Math.ceil(clearance.length / 8))
for (let index = 0; index < clearance.length; index += 1) {
  if (clearance[index]) packed[index >> 3] |= 1 << (index & 7)
}
const chunks = Buffer.from(packed).toString('base64').match(/.{1,120}/g) || []
const moduleSource = `// Generated by scripts/build-world-map-flat-v2-collision.mjs. Do not edit by hand.
export const WORLD_FLAT_V2_WALKABLE_MASK_META = Object.freeze({
  width: ${WIDTH},
  height: ${HEIGHT},
  cellSize: ${CELL_SIZE},
  worldWidth: ${WORLD_MAP_V4.width},
  worldHeight: ${WORLD_MAP_V4.height},
  bitOrder: 'little',
  source: 'modular-v4-colliders-with-flat-v2-home-registration',
  clearance: Object.freeze({ halfWidth: ${WORLD_PLAYER_FOOT_CLEARANCE.halfWidth}, halfHeight: ${WORLD_PLAYER_FOOT_CLEARANCE.halfHeight} }),
})

export const WORLD_FLAT_V2_WALKABLE_MASK_BASE64 = [
${chunks.map(chunk => `  '${chunk}',`).join('\n')}
].join('')
`

const walkable = Uint8Array.from(clearance, value => value ? 255 : 0)
const debug = Buffer.alloc(clearance.length * 4)
for (let index = 0; index < clearance.length; index += 1) {
  const color = clearance[index] ? [36, 214, 96, 112] : [228, 58, 64, 112]
  debug.set(color, index * 4)
}
const [walkablePng, debugPng] = await Promise.all([
  sharp(Buffer.from(walkable), { raw: { width: WIDTH, height: HEIGHT, channels: 1 } }).png().toBuffer(),
  sharp(debug, { raw: { width: WIDTH, height: HEIGHT, channels: 4 } }).png().toBuffer(),
])
const walkableCells = clearance.reduce((sum, value) => sum + value, 0)
const report = {
  status: 'PASS',
  source: 'modular-v4-colliders-with-flat-v2-home-registration',
  width: WIDTH,
  height: HEIGHT,
  cellSize: CELL_SIZE,
  totalCells: clearance.length,
  walkableCells,
  blockedCells: clearance.length - walkableCells,
  homeCollider: WORLD_MAP_FLAT_V2_COLLISION_HOME,
}

await mkdir(OUTPUT, { recursive: true })
await Promise.all([
  writeFile(MODULE, moduleSource),
  writeFile(path.join(OUTPUT, 'walkable-clearance-mask.png'), walkablePng),
  writeFile(path.join(OUTPUT, 'collision-debug.png'), debugPng),
  writeFile(path.join(OUTPUT, 'collision-build.json'), `${JSON.stringify(report, null, 2)}\n`),
])

console.log(JSON.stringify(report, null, 2))

