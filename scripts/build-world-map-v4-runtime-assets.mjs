import { createHash } from 'node:crypto'
import { access, mkdir, readFile, stat, unlink, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import sharp from 'sharp'
import { WORLD_MAP_V4_ADDITIVE_SOURCE_ASSETS } from '../data/world-map-v4/sourceAssets.mjs'
import { WORLD_MAP_V4_ASSETS, WORLD_MAP_V4_PREVIEW } from '../lib/worldMapV4Assets.mjs'
import { WORLD_MAP_V4_FOREGROUND, WORLD_MAP_V4_OBJECTS, WORLD_MAP_V4_TERRAIN_PANELS } from '../lib/worldMapV4Manifest.mjs'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const SOURCE_DIR = path.join(ROOT, 'public/assets/world/sound-archive-garden-v4')
const OUTPUT_DIR = path.join(SOURCE_DIR, 'runtime')
const ASSET_MODULE = path.join(ROOT, 'lib/worldMapV4Assets.mjs')
const args = new Set(process.argv.slice(2))
for (const argument of args) {
  if (argument !== '--check') throw new Error(`Unknown argument: ${argument}`)
}
const checkOnly = args.has('--check')
const sha256 = value => createHash('sha256').update(value).digest('hex')

await mkdir(OUTPUT_DIR, { recursive: true })

function assetModuleSource(records, preview) {
  const lines = [
    '// Generated by scripts/build-world-map-v4-runtime-assets.mjs. Do not edit by hand.',
    'export const WORLD_MAP_V4_ASSETS = Object.freeze({',
  ]
  for (const record of records) {
    lines.push(`  ${JSON.stringify(record.id)}: Object.freeze({ src: ${JSON.stringify(record.src)}, width: ${record.width}, height: ${record.height}, hasAlpha: ${record.hasAlpha}, category: ${JSON.stringify(record.category)}, bytes: ${record.bytes}, decodedRGBA: ${record.decodedRGBA} }),`)
  }
  lines.push(
    '})',
    '',
    'export const WORLD_MAP_V4_ASSET_IDS = Object.freeze(Object.keys(WORLD_MAP_V4_ASSETS))',
    '',
    `export const WORLD_MAP_V4_PREVIEW = Object.freeze({ src: ${JSON.stringify(preview.src)}, width: ${preview.width}, height: ${preview.height}, bytes: ${preview.bytes}, decodedRGBA: ${preview.width * preview.height * 4} })`,
    '',
  )
  return `${lines.join('\n')}\n`
}

async function verifyApprovedSource(asset) {
  const filename = path.join(ROOT, asset.sourcePath)
  const [bytes, metadata] = await Promise.all([readFile(filename), sharp(filename).metadata()])
  if (sha256(bytes) !== asset.sha256) throw new Error(`Approved source hash differs for ${asset.id}`)
  if (metadata.width !== asset.width || metadata.height !== asset.height) throw new Error(`Approved source dimensions differ for ${asset.id}`)
  if (metadata.channels !== 4 || metadata.hasAlpha !== true) throw new Error(`Approved source must remain RGBA for ${asset.id}`)
  return { filename, sourceBytes: bytes.length }
}

async function materializeAdditiveAsset(asset) {
  const source = await verifyApprovedSource(asset)
  const output = path.join(OUTPUT_DIR, `${asset.id}.webp`)
  if (!checkOnly) {
    await sharp(source.filename)
      .webp({ quality: 92, alphaQuality: 100, effort: 6, smartSubsample: true })
      .toFile(output)
  }
  const [info, metadata] = await Promise.all([stat(output), sharp(output).metadata()])
  if (metadata.width !== asset.width || metadata.height !== asset.height) throw new Error(`Runtime dimensions differ for ${asset.id}`)
  return {
    id: asset.id,
    src: `/assets/world/sound-archive-garden-v4/runtime/${asset.id}.webp`,
    width: metadata.width,
    height: metadata.height,
    hasAlpha: asset.hasAlpha,
    category: asset.category,
    sourceBytes: source.sourceBytes,
    bytes: info.size,
    decodedRGBA: metadata.width * metadata.height * 4,
  }
}

async function recordForMaterializedAsset(id, asset) {
  const filename = path.join(ROOT, 'public', asset.src)
  const [info, metadata] = await Promise.all([stat(filename), sharp(filename).metadata()])
  if (metadata.width !== asset.width || metadata.height !== asset.height) throw new Error(`Runtime dimensions differ for ${id}`)
  return {
    id,
    src: asset.src,
    width: metadata.width,
    height: metadata.height,
    hasAlpha: asset.hasAlpha,
    category: asset.category,
    bytes: info.size,
    decodedRGBA: metadata.width * metadata.height * 4,
  }
}

const additiveIds = new Set(WORLD_MAP_V4_ADDITIVE_SOURCE_ASSETS.map(asset => asset.id))
const additiveRecords = []
for (const asset of WORLD_MAP_V4_ADDITIVE_SOURCE_ASSETS) additiveRecords.push(await materializeAdditiveAsset(asset))

let fullBuild = true
try {
  await access(path.join(SOURCE_DIR, 'terrain-underlay.png'))
} catch {
  fullBuild = false
}

let records
let preview
if (!fullBuild) {
  const existingRecords = []
  for (const [id, asset] of Object.entries(WORLD_MAP_V4_ASSETS)) {
    if (!additiveIds.has(id)) existingRecords.push(await recordForMaterializedAsset(id, asset))
  }
  records = [...existingRecords, ...additiveRecords]
  const previewInfo = await stat(path.join(ROOT, 'public', WORLD_MAP_V4_PREVIEW.src))
  preview = { ...WORLD_MAP_V4_PREVIEW, bytes: previewInfo.size }
} else {
  const displaySizes = new Map()
  for (const panel of WORLD_MAP_V4_TERRAIN_PANELS) displaySizes.set(panel.assetId, { width: panel.width, height: panel.height })
  for (const object of [...WORLD_MAP_V4_OBJECTS, ...WORLD_MAP_V4_FOREGROUND]) {
    displaySizes.set(object.assetId, { width: Math.ceil(object.width), height: Math.ceil(object.height) })
  }
  for (const asset of WORLD_MAP_V4_ADDITIVE_SOURCE_ASSETS) displaySizes.set(asset.id, { width: asset.width, height: asset.height })

  const baseDefinitions = Object.entries(WORLD_MAP_V4_ASSETS).filter(([id]) => !additiveIds.has(id))
  records = []
  for (const [id, asset] of baseDefinitions) {
    const source = path.join(SOURCE_DIR, `${id}.png`)
    const targetSize = displaySizes.get(id)
    if (!targetSize) throw new Error(`No runtime display size for ${id}`)
    const output = path.join(OUTPUT_DIR, `${id}.webp`)
    if (!checkOnly) {
      await sharp(source)
        .resize(targetSize.width, targetSize.height, { fit: 'fill', kernel: sharp.kernel.lanczos3 })
        .webp({ quality: 92, alphaQuality: 100, effort: 6, smartSubsample: true })
        .toFile(output)
    }
    records.push(await recordForMaterializedAsset(id, { ...asset, src: `/assets/world/sound-archive-garden-v4/runtime/${id}.webp`, width: targetSize.width, height: targetSize.height }))
  }
  records.push(...additiveRecords)

  const previewOutput = path.join(OUTPUT_DIR, 'terrain-preview.webp')
  if (!checkOnly) {
    await sharp(path.join(SOURCE_DIR, 'terrain-underlay.png'))
      .resize(480, 360, { fit: 'fill', kernel: sharp.kernel.lanczos3 })
      .webp({ quality: 68, effort: 6, smartSubsample: true })
      .toFile(previewOutput)
  }
  const previewInfo = await stat(previewOutput)
  preview = { src: '/assets/world/sound-archive-garden-v4/runtime/terrain-preview.webp', width: 480, height: 360, bytes: previewInfo.size }
}

const moduleSource = assetModuleSource(records, preview)
if (checkOnly) {
  const current = await readFile(ASSET_MODULE, 'utf8')
  if (current !== moduleSource) throw new Error(`Generated output is stale: ${ASSET_MODULE}`)
} else {
  await writeFile(ASSET_MODULE, moduleSource)
}

const summary = {
  status: 'PASS',
  mode: checkOnly ? 'check' : fullBuild ? 'full-build-with-additive-assets' : 'additive-build',
  assetCount: records.length + 1,
  registryAssetCount: records.length,
  existingRuntimeAssetsReencoded: fullBuild && !checkOnly ? records.length - additiveRecords.length : 0,
  additiveAssets: additiveRecords,
  bytes: records.reduce((sum, record) => sum + record.bytes, 0) + preview.bytes,
  decodedRGBA: records.reduce((sum, record) => sum + record.decodedRGBA, 0) + preview.width * preview.height * 4,
  preview,
}
if (fullBuild && !checkOnly) {
  for (const [id] of Object.entries(WORLD_MAP_V4_ASSETS)) {
    if (!additiveIds.has(id)) await unlink(path.join(SOURCE_DIR, `${id}.png`)).catch(() => {})
  }
  await unlink(path.join(SOURCE_DIR, 'terrain-underlay.png')).catch(() => {})
}

console.log(JSON.stringify(summary, null, 2))
