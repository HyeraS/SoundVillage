import { access, mkdir, stat, unlink, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import sharp from 'sharp'
import { WORLD_MAP_V4_ASSETS } from '../lib/worldMapV4Assets.mjs'
import { WORLD_MAP_V4_FOREGROUND, WORLD_MAP_V4_OBJECTS, WORLD_MAP_V4_TERRAIN_PANELS } from '../lib/worldMapV4Manifest.mjs'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const SOURCE_DIR = path.join(ROOT, 'public/assets/world/sound-archive-garden-v4')
const OUTPUT_DIR = path.join(SOURCE_DIR, 'runtime')
const REVIEW_DIR = path.join(ROOT, '_review/world-map-sequential-fix-2026-09-21/04-assets')
const ASSET_MODULE = path.join(ROOT, 'lib/worldMapV4Assets.mjs')
await mkdir(OUTPUT_DIR, { recursive: true })
await mkdir(REVIEW_DIR, { recursive: true })

// The large PNG masters are generated intermediates, not production assets.
// Once optimized WebPs exist they are intentionally removed from public/.
// Running this command in that steady state validates the materialized set;
// run build-world-map-v4-assets.py first when a full rebuild is required.
try {
  await access(path.join(SOURCE_DIR, 'terrain-underlay.png'))
} catch {
  const verified = []
  for (const [id, asset] of Object.entries(WORLD_MAP_V4_ASSETS)) {
    const filename = path.join(ROOT, 'public', asset.src)
    const [info, metadata] = await Promise.all([stat(filename), sharp(filename).metadata()])
    if (metadata.width !== asset.width || metadata.height !== asset.height) throw new Error(`Runtime dimensions differ for ${id}`)
    verified.push({ id, bytes:info.size, width:metadata.width, height:metadata.height })
  }
  console.log(JSON.stringify({ status:'PASS', mode:'verify-materialized-runtime', assetCount:verified.length, bytes:verified.reduce((sum, asset) => sum + asset.bytes, 0), rebuildHint:'Run scripts/build-world-map-v4-assets.py before this command to regenerate from PNG masters.' }, null, 2))
  process.exit(0)
}

const displaySizes = new Map()
for (const panel of WORLD_MAP_V4_TERRAIN_PANELS) displaySizes.set(panel.assetId, { width: panel.width, height: panel.height })
for (const object of [...WORLD_MAP_V4_OBJECTS, ...WORLD_MAP_V4_FOREGROUND]) {
  displaySizes.set(object.assetId, { width: Math.ceil(object.width), height: Math.ceil(object.height) })
}

const records = []
for (const [id, asset] of Object.entries(WORLD_MAP_V4_ASSETS)) {
  if (id === 'terrain-underlay') continue
  const source = path.join(SOURCE_DIR, `${id}.png`)
  const targetSize = displaySizes.get(id)
  if (!targetSize) throw new Error(`No runtime display size for ${id}`)
  const output = path.join(OUTPUT_DIR, `${id}.webp`)
  await sharp(source)
    .resize(targetSize.width, targetSize.height, { fit: 'fill', kernel: sharp.kernel.lanczos3 })
    .webp({ quality: 92, alphaQuality: 100, effort: 6, smartSubsample: true })
    .toFile(output)
  const [before, after, metadata] = await Promise.all([stat(source), stat(output), sharp(output).metadata()])
  records.push({
    id,
    src: `/assets/world/sound-archive-garden-v4/runtime/${id}.webp`,
    width: metadata.width,
    height: metadata.height,
    hasAlpha: asset.hasAlpha,
    category: asset.category,
    beforeBytes: before.size,
    bytes: after.size,
    decodedRGBA: metadata.width * metadata.height * 4,
  })
}

const previewOutput = path.join(OUTPUT_DIR, 'terrain-preview.webp')
await sharp(path.join(SOURCE_DIR, 'terrain-underlay.png'))
  .resize(480, 360, { fit: 'fill', kernel: sharp.kernel.lanczos3 })
  .webp({ quality: 68, effort: 6, smartSubsample: true })
  .toFile(previewOutput)
const previewInfo = await stat(previewOutput)

const summary = {
  status: 'PASS',
  assetCount: records.length,
  beforeBytes: records.reduce((sum, record) => sum + record.beforeBytes, 0),
  bytes: records.reduce((sum, record) => sum + record.bytes, 0),
  decodedRGBA: records.reduce((sum, record) => sum + record.decodedRGBA, 0),
  preview: { src: '/assets/world/sound-archive-garden-v4/runtime/terrain-preview.webp', width: 480, height: 360, bytes: previewInfo.size },
  records,
}
summary.reduction = 1 - summary.bytes / summary.beforeBytes
const moduleLines = [
  '// Generated by scripts/build-world-map-v4-runtime-assets.mjs. Do not edit by hand.',
  'export const WORLD_MAP_V4_ASSETS = Object.freeze({',
]
for (const record of records) {
  moduleLines.push(`  ${JSON.stringify(record.id)}: Object.freeze({ src: ${JSON.stringify(record.src)}, width: ${record.width}, height: ${record.height}, hasAlpha: ${record.hasAlpha}, category: ${JSON.stringify(record.category)}, bytes: ${record.bytes}, decodedRGBA: ${record.decodedRGBA} }),`)
}
moduleLines.push(
  '})',
  '',
  'export const WORLD_MAP_V4_ASSET_IDS = Object.freeze(Object.keys(WORLD_MAP_V4_ASSETS))',
  '',
  `export const WORLD_MAP_V4_PREVIEW = Object.freeze({ src: ${JSON.stringify(summary.preview.src)}, width: ${summary.preview.width}, height: ${summary.preview.height}, bytes: ${summary.preview.bytes}, decodedRGBA: ${summary.preview.width * summary.preview.height * 4} })`,
  '',
)
await Promise.all([
  writeFile(path.join(REVIEW_DIR, 'runtime-asset-build.json'), `${JSON.stringify(summary, null, 2)}\n`),
  writeFile(ASSET_MODULE, `${moduleLines.join('\n')}\n`),
])
// Public PNGs are build intermediates. Keep the authored masters under
// design/, then remove only the materialized intermediates after every
// runtime asset has been verified above.
for (const record of records) {
  await unlink(path.join(SOURCE_DIR, `${record.id}.png`)).catch(() => {})
}
await unlink(path.join(SOURCE_DIR, 'terrain-underlay.png')).catch(() => {})
console.log(JSON.stringify(summary, null, 2))
