import crypto from 'node:crypto'
import fs from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import sharp from 'sharp'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const SOURCE_ASSET = 'public/assets/world/music-village/navigation/music-walkable-mask.png'
const OUTPUT_MODULE = 'lib/generated/musicVillageWalkableMask.mjs'
const WIDTH = 384
const HEIGHT = 288
const CELL_SIZE = 4
const WORLD_WIDTH = 1536
const WORLD_HEIGHT = 1152

function fail(message) {
  throw new Error(`Music Village navigation mask: ${message}`)
}

function formatBase64(value, width = 120) {
  return value.match(new RegExp(`.{1,${width}}`, 'g')).map((line) => `  '${line}'`).join(' +\n')
}

async function buildModule() {
  const sourcePath = path.join(ROOT, SOURCE_ASSET)
  const source = await fs.readFile(sourcePath)
  const image = sharp(source, { failOn: 'error', limitInputPixels: WIDTH * HEIGHT })
  const metadata = await image.metadata()
  if (metadata.format !== 'png') fail(`expected PNG, received ${metadata.format || 'unknown format'}`)
  if (metadata.width !== WIDTH || metadata.height !== HEIGHT) {
    fail(`expected ${WIDTH}x${HEIGHT}, received ${metadata.width}x${metadata.height}`)
  }

  const { data, info } = await image.ensureAlpha().raw().toBuffer({ resolveWithObject: true })
  if (info.channels !== 4) fail(`expected RGBA decode, received ${info.channels} channels`)

  const bitset = Buffer.alloc(Math.ceil(WIDTH * HEIGHT / 8))
  let blackCells = 0
  let whiteCells = 0
  for (let index = 0; index < WIDTH * HEIGHT; index++) {
    const offset = index * 4
    const red = data[offset]
    const green = data[offset + 1]
    const blue = data[offset + 2]
    const alpha = data[offset + 3]
    const x = index % WIDTH
    const y = Math.floor(index / WIDTH)
    if (alpha !== 255) fail(`transparent pixel at (${x}, ${y}); alpha=${alpha}`)
    const black = red === 0 && green === 0 && blue === 0
    const white = red === 255 && green === 255 && blue === 255
    if (!black && !white) fail(`non-binary pixel at (${x}, ${y}); rgba(${red}, ${green}, ${blue}, ${alpha})`)
    if (white) {
      bitset[index >> 3] |= 1 << (7 - (index & 7))
      whiteCells++
    } else {
      blackCells++
    }
  }

  const sha256 = crypto.createHash('sha256').update(source).digest('hex')
  const base64 = bitset.toString('base64')
  const moduleSource = `// Generated by scripts/build-music-village-navigation-mask.mjs. Do not edit by hand.\n` +
`export const MUSIC_VILLAGE_MASK_METADATA = Object.freeze({\n` +
`  width: ${WIDTH},\n` +
`  height: ${HEIGHT},\n` +
`  cellSize: ${CELL_SIZE},\n` +
`  worldWidth: ${WORLD_WIDTH},\n` +
`  worldHeight: ${WORLD_HEIGHT},\n` +
`  sourceAsset: '${SOURCE_ASSET}',\n` +
`  sha256: '${sha256}',\n` +
`  encoding: '1-bit-msb-row-major-base64',\n` +
`  whiteCells: ${whiteCells},\n` +
`  blackCells: ${blackCells},\n` +
`})\n\n` +
`const WALKABLE_BITS_BASE64 =\n${formatBase64(base64)}\n` +
`const WALKABLE_BYTES = Uint8Array.from(globalThis.atob(WALKABLE_BITS_BASE64), (value) => value.charCodeAt(0))\n\n` +
`export function isMusicVillageMaskCellWalkable(col, row) {\n` +
`  if (!Number.isInteger(col) || !Number.isInteger(row) || col < 0 || row < 0 || col >= MUSIC_VILLAGE_MASK_METADATA.width || row >= MUSIC_VILLAGE_MASK_METADATA.height) return false\n` +
`  const index = row * MUSIC_VILLAGE_MASK_METADATA.width + col\n` +
`  return Boolean(WALKABLE_BYTES[index >> 3] & (1 << (7 - (index & 7))))\n` +
`}\n`

  return { moduleSource, sha256, whiteCells, blackCells, bytes: bitset.length }
}

const { moduleSource, ...summary } = await buildModule()
const outputPath = path.join(ROOT, OUTPUT_MODULE)
if (process.argv.includes('--check')) {
  const existing = await fs.readFile(outputPath, 'utf8').catch(() => '')
  if (existing !== moduleSource) fail(`${OUTPUT_MODULE} is missing or stale; run npm run build:music-navigation-mask`)
  console.log(JSON.stringify({ ok: true, mode: 'check', sourceAsset: SOURCE_ASSET, outputModule: OUTPUT_MODULE, ...summary }, null, 2))
} else {
  await fs.mkdir(path.dirname(outputPath), { recursive: true })
  await fs.writeFile(outputPath, moduleSource)
  console.log(JSON.stringify({ ok: true, mode: 'write', sourceAsset: SOURCE_ASSET, outputModule: OUTPUT_MODULE, ...summary }, null, 2))
}
