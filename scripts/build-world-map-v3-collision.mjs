import { mkdir, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import sharp from 'sharp'
import {
  WORLD_MAP_V3,
  WORLD_MAP_V3_FOREGROUND,
  WORLD_MAP_V3_OBJECTS,
  WORLD_MAP_V3_PATHS,
  WORLD_MAP_V3_TERRAIN,
} from '../lib/worldMapV3Manifest.mjs'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const OUTPUT = path.join(ROOT, 'public/assets/world/sound-archive-garden-v3')
const MODULE = path.join(ROOT, 'lib/worldWalkableMaskData.mjs')
const CELL = 4
const WIDTH = WORLD_MAP_V3.width / CELL
const HEIGHT = WORLD_MAP_V3.height / CELL
const FOOT_HALF_W = 14
const FOOT_HALF_H = 8

const clamp = (value, min, max) => Math.max(min, Math.min(max, value))

function segmentDistanceSquared(px, py, a, b) {
  const vx = b.x - a.x
  const vy = b.y - a.y
  const lengthSquared = vx * vx + vy * vy || 1
  const t = clamp(((px - a.x) * vx + (py - a.y) * vy) / lengthSquared, 0, 1)
  const dx = px - (a.x + vx * t)
  const dy = py - (a.y + vy * t)
  return dx * dx + dy * dy
}

function onPaintedTerrain(x, y) {
  const plaza = WORLD_MAP_V3_TERRAIN.plaza
  const nx = (x - plaza.cx) / plaza.rx
  const ny = (y - plaza.cy) / plaza.ry
  if (nx * nx + ny * ny <= 1) return true
  return WORLD_MAP_V3_PATHS.some(route => {
    const radiusSquared = (route.width / 2) ** 2
    for (let index = 1; index < route.points.length; index += 1) {
      if (segmentDistanceSquared(x, y, route.points[index - 1], route.points[index]) <= radiusSquared) return true
    }
    return false
  })
}

const colliders = [...WORLD_MAP_V3_OBJECTS, ...WORLD_MAP_V3_FOREGROUND].flatMap(object =>
  object.collision.map((collider, index) => ({
    id: `${object.id}:${index}`,
    x: object.x + collider.x,
    y: object.y + collider.y,
    w: collider.w,
    h: collider.h,
  })),
)

function inObstacle(x, y) {
  return colliders.some(collider => x >= collider.x && x <= collider.x + collider.w && y >= collider.y && y <= collider.y + collider.h)
}

function footFits(x, y) {
  for (let oy = -FOOT_HALF_H; oy <= FOOT_HALF_H; oy += CELL) {
    for (let ox = -FOOT_HALF_W; ox <= FOOT_HALF_W; ox += CELL) {
      const sx = x + ox
      const sy = y + oy
      if (!onPaintedTerrain(sx, sy) || inObstacle(sx, sy)) return false
    }
  }
  return true
}

const raw = new Uint8Array(WIDTH * HEIGHT)
const clearance = new Uint8Array(WIDTH * HEIGHT)
const obstacle = new Uint8Array(WIDTH * HEIGHT)
for (let cy = 0; cy < HEIGHT; cy += 1) {
  for (let cx = 0; cx < WIDTH; cx += 1) {
    const index = cy * WIDTH + cx
    const x = cx * CELL + CELL / 2
    const y = cy * CELL + CELL / 2
    raw[index] = onPaintedTerrain(x, y) ? 1 : 0
    obstacle[index] = inObstacle(x, y) ? 1 : 0
    clearance[index] = footFits(x, y) ? 1 : 0
  }
}

const packed = new Uint8Array(Math.ceil(clearance.length / 8))
for (let index = 0; index < clearance.length; index += 1) {
  if (clearance[index]) packed[index >> 3] |= 1 << (index & 7)
}

const rgba = Buffer.alloc(WIDTH * HEIGHT * 4)
const mask = Buffer.alloc(WIDTH * HEIGHT)
const obstacleMask = Buffer.alloc(WIDTH * HEIGHT)
for (let index = 0; index < clearance.length; index += 1) {
  mask[index] = clearance[index] ? 255 : 0
  obstacleMask[index] = obstacle[index] ? 255 : 0
  const offset = index * 4
  if (clearance[index]) {
    rgba[offset] = 36; rgba[offset + 1] = 210; rgba[offset + 2] = 92; rgba[offset + 3] = 116
  } else if (obstacle[index]) {
    rgba[offset] = 235; rgba[offset + 1] = 55; rgba[offset + 2] = 64; rgba[offset + 3] = 176
  } else if (raw[index]) {
    rgba[offset] = 250; rgba[offset + 1] = 178; rgba[offset + 2] = 46; rgba[offset + 3] = 130
  }
}

await mkdir(OUTPUT, { recursive: true })
await Promise.all([
  sharp(mask, { raw: { width: WIDTH, height: HEIGHT, channels: 1 } }).png().toFile(path.join(OUTPUT, 'walkable-clearance-mask.png')),
  sharp(obstacleMask, { raw: { width: WIDTH, height: HEIGHT, channels: 1 } }).png().toFile(path.join(OUTPUT, 'obstacle-mask.png')),
  sharp(rgba, { raw: { width: WIDTH, height: HEIGHT, channels: 4 } }).png().toFile(path.join(OUTPUT, 'collision-debug.png')),
])

const moduleSource = `// Generated by scripts/build-world-map-v3-collision.mjs. Do not edit by hand.\n` +
  `export const WORLD_WALKABLE_MASK_META = Object.freeze({ width: ${WIDTH}, height: ${HEIGHT}, cellSize: ${CELL}, worldWidth: ${WORLD_MAP_V3.width}, worldHeight: ${WORLD_MAP_V3.height}, source: 'world-map-v3-manifest' })\n` +
  `export const WORLD_WALKABLE_MASK_BASE64 = '${Buffer.from(packed).toString('base64')}'\n`
await writeFile(MODULE, moduleSource)

const result = {
  source: 'lib/worldMapV3Manifest.mjs',
  cellSize: CELL,
  width: WIDTH,
  height: HEIGHT,
  rawWalkableCells: raw.reduce((sum, value) => sum + value, 0),
  clearanceCells: clearance.reduce((sum, value) => sum + value, 0),
  obstacleCells: obstacle.reduce((sum, value) => sum + value, 0),
  colliderCount: colliders.length,
}
await writeFile(path.join(OUTPUT, 'collision-build.json'), JSON.stringify(result, null, 2) + '\n')
console.log(JSON.stringify(result, null, 2))
